/** Deterministic hashing in place of Math.random(): the same inputs give the same frame every render. */
export function hash(...xs: number[]): number {
  let h = 0x9e3779b9;
  for (const x of xs) {
    h = Math.imul(h ^ (x | 0), 0x85ebca6b);
    h ^= h >>> 13;
    h = Math.imul(h, 0xc2b2ae35);
    h ^= h >>> 16;
  }
  return h >>> 0;
}

/** A float in [0, 1) from the inputs. */
export const rand = (...xs: number[]) => hash(...xs) / 4294967296;

/** A stable number for a string, for seeding per element. */
export function seedOf(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}
