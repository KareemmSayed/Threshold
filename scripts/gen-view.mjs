// Generates src/view/assets.ts from src/view/client/ so the Worker serves the view's CSS and
// script inline, with no build step. Run after editing either file: npm run gen:view
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../src/view/", import.meta.url);
const css = readFileSync(new URL("client/view.css", dir), "utf8");
const js = readFileSync(new URL("client/view.js", dir), "utf8");
for (const [name, text] of [["view.css", css], ["view.js", js]]) {
  if (/<\/(style|script)/i.test(text)) throw new Error(`${name} contains a closing style or script tag; it would end the inline block early.`);
}

const src = `// Generated by scripts/gen-view.mjs from src/view/client/. Do not edit; run npm run gen:view.
export const VIEW_CSS = ${JSON.stringify(css)};

export const VIEW_JS = ${JSON.stringify(js)};
`;
writeFileSync(new URL("assets.ts", dir), src);
console.log("wrote src/view/assets.ts", src.length, "bytes");
