// Generates src/fit/profile.ts from Garmin's FIT SDK so the runtime decoder ships
// only the field tables it needs, with Garmin's own names, scales and offsets.
// Run: node scripts/gen-fit-profile.mjs
import { writeFileSync } from "node:fs";
import { Profile } from "@garmin/fitsdk";

const MESSAGES = { 0: "fileId", 7: "zonesTarget", 12: "sport", 18: "session", 19: "lap", 216: "timeInZone" };
const STRING_TYPES = new Set(["string"]);

const first = (v) => (Array.isArray(v) ? v[0] : v);
const fields = {};
for (const num of Object.keys(MESSAGES)) {
  const out = {};
  for (const f of Object.values(Profile.messages[num].fields)) {
    const scale = Number(first(f.scale) ?? 1) || 1;
    const offset = Number(first(f.offset) ?? 0) || 0;
    const kind = STRING_TYPES.has(f.baseType) ? "s" : f.type === "dateTime" ? "t" : Profile.types[f.type] && f.type !== "dateTime" ? "e" : "n";
    out[f.num] = [f.name, scale, offset, kind, kind === "e" ? f.type : ""];
  }
  fields[num] = out;
}

const enums = {};
for (const name of ["sport", "subSport", "hrZoneCalc", "pwrZoneCalc", "mesgNum", "file", "intensity", "lapTrigger"]) {
  enums[name] = Object.fromEntries(Object.entries(Profile.types[name]).filter(([k]) => /^\d+$/.test(k)));
}

const src = `// Generated by scripts/gen-fit-profile.mjs from @garmin/fitsdk ${Profile.version.major}.${Profile.version.minor}. Do not edit.
/** [name, scale, offset, kind (n=number, e=enum, t=FIT timestamp, s=string), enum type] */
export type FieldSpec = [string, number, number, "n" | "e" | "t" | "s", string];

export const MESSAGE_NAMES: Record<number, string> = ${JSON.stringify(MESSAGES)};

export const FIELDS: Record<number, Record<number, FieldSpec>> = ${JSON.stringify(fields)};

export const ENUMS: Record<string, Record<string, string>> = ${JSON.stringify(enums)};
`;
writeFileSync(new URL("../src/fit/profile.ts", import.meta.url), src);
console.log("wrote src/fit/profile.ts", src.length, "bytes");
